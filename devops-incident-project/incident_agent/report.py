"""Plain-text incident report: evidence first, then what is known vs assumed."""
from .models import ASSUMED, INFERRED, OBSERVED


def render_llm(analysis, model):
    out = ["", "AI ANALYSIS (local model '%s' via Ollama) - generated by a language model, validated, NOT verified" % model,
           "=" * 70]
    if not analysis.causes:
        out.append("  Probable causes: none reported")
    for c in analysis.causes:
        label = {"supported": "FACT (cites existing evidence)", "unsupported": "UNSUPPORTED",
                 "assumption": "ASSUMPTION"}[c.status]
        cites = ", ".join(c.evidence_ids) or "no evidence cited"
        out.append("  - [%s | %s confidence | %s] %s" % (label, c.confidence, cites, c.claim))
        if c.note and c.status == "unsupported":
            out.append("      validation: %s" % c.note)
    if analysis.fixes:
        out.append("  Suggested fixes (never run by this tool):")
        for f in analysis.fixes:
            out.append("    * %s" % f.description)
            if f.command:
                tag = "read-only" if f.command_class == "read-only" else "NOT RUN - not a read-only command"
                out.append("        command (%s): %s" % (tag, f.command))
    if analysis.verification:
        out.append("  Verification commands (run them yourself):")
        for cmd, cls in analysis.verification:
            out.append("    $ %s%s" % (cmd, "" if cls == "read-only" else "    <- NOT read-only, review before use"))
    for p in analysis.problems:
        out.append("  note: %s" % p)
    return "\n".join(out)


def render(diag):
    out = ["INCIDENT DIAGNOSIS", "=" * 18, diag.summary, ""]

    out.append("EVIDENCE COLLECTED")
    for ev in diag.evidence:
        mark = "  [could not read]" if ev.error else ""
        out.append("  %s  (%s) %s%s" % (ev.id, ev.source, ev.summary, mark))
    out.append("")

    for kind, title in ((OBSERVED, "OBSERVED - stated directly by the evidence"),
                        (INFERRED, "INFERRED - reasoned from the evidence, not proven"),
                        (ASSUMED, "ASSUMED - no evidence either way")):
        group = [f for f in diag.findings if f.kind == kind]
        if not group:
            continue
        out.append(title)
        for f in group:
            cites = ("cites " + ", ".join(f.evidence_ids)) if f.evidence_ids else "no evidence"
            out.append("  - %s  [%s confidence; %s]" % (f.claim, f.confidence, cites))
            if f.reasoning:
                out.append("      why: %s" % f.reasoning)
        out.append("")

    out.append("UNKNOWNS - what could not be determined")
    out.extend("  - %s" % u for u in diag.unknowns) if diag.unknowns else out.append("  (none)")
    out.append("")

    out.append("REMEDIATION PLAN - nothing below runs without your explicit approval")
    if not diag.actions:
        out.append("  (no actions suggested)")
    for a in diag.actions:
        kind = "CHANGES ENVIRONMENT" if a.changes_environment else ("read-only" if a.command else "manual step")
        out.append("  %s [%s] %s" % (a.id, kind, a.description))
        if a.command:
            out.append("      command: %s" % " ".join(a.command))
        if a.rationale:
            out.append("      reason:  %s" % a.rationale)
    return "\n".join(out)
